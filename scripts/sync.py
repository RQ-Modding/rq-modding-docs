#!/usr/bin/env python3
"""Copies what the docs take from the engine repo.

  python -I -X utf8 scripts/sync.py [--engine PATH] [--check]

  docs/reference/      the API reference, generated from the engine's dist/lua/rq.lua by
                       tools/apidoc/rqdoc.py (never edit these pages by hand)
  docs/changelog.md    the engine's CHANGELOG.md
  docs/data/           tables of the game's numbers and rq.ids keys, from the engine's
                       data/ids/ids.json (made by tools/ids/gen_ids.py)
  docs/.vitepress/engine.json   the loader version and engine commit the pages came from

--engine defaults to ../RQ_modding_xsystem4 (the workspace layout). --check writes nothing and
exits 1 when the committed pages differ from what the engine would give.
Standard library only.
"""
import filecmp
import json
import os
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(ROOT, "docs")


def generate(engine, out):
    """Writes reference/, changelog.md, data/ and engine.json under out (a docs-shaped folder)."""
    rq_lua = os.path.join(engine, "dist", "lua", "rq.lua")
    rqdoc = os.path.join(engine, "tools", "apidoc", "rqdoc.py")
    for p in (rq_lua, rqdoc):
        if not os.path.isfile(p):
            sys.exit("sync: not found: " + p)
    ref = os.path.join(out, "reference")
    subprocess.run([sys.executable, "-I", "-X", "utf8", rqdoc, "md", rq_lua, ref],
                   check=True, stdout=subprocess.DEVNULL)

    with open(os.path.join(engine, "CHANGELOG.md"), encoding="utf-8") as f:
        log = f.read()
    with open(os.path.join(out, "changelog.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("<!-- Copied from the engine's CHANGELOG.md by scripts/sync.py. Edit it there. -->\n\n")
        f.write(log.replace("\r\n", "\n"))

    subprocess.run([sys.executable, "-I", "-X", "utf8", rqdoc, "json", rq_lua, os.path.join(out, "_model.json")],
                           check=True, stdout=subprocess.DEVNULL)
    with open(os.path.join(out, "_model.json"), encoding="utf-8") as f:
        version = json.load(f)["version"]
    os.remove(os.path.join(out, "_model.json"))
    try:
        commit = subprocess.run(["git", "-C", engine, "rev-parse", "--short", "HEAD"], check=True,
                                capture_output=True, text=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        commit = ""
    write_data(engine, out)
    os.makedirs(os.path.join(out, ".vitepress"), exist_ok=True)
    with open(os.path.join(out, ".vitepress", "engine.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump({"version": version, "commit": commit}, f, indent=2)
        f.write("\n")


DATA_PAGES = {"chara": "characters", "chara_type": "chara-types", "class": "classes",
              "element": "elements", "item": "items", "item_kind": "item-kinds", "map_kind": "map-kinds", "monster": "monsters", "music": "music", "quest": "quests",
              "race": "races", "skill": "skills", "state": "states", "target": "targets"}
DETAIL = {"chara": "Class", "item": "Slot", "map_kind": "Places", "monster": "Level, race", "skill": "Kind", "target": "In the game"}


def cell(s):
    # the game writes é in its own font code; the tables show the letter
    return s.replace("･", "é").replace("|", "\\|")


def write_data(engine, out):
    src = os.path.join(engine, "data", "ids", "ids.json")
    if not os.path.isfile(src):
        sys.exit("sync: not found: " + src)
    with open(src, encoding="utf-8") as f:
        model = json.load(f)
    data = os.path.join(out, "data")
    os.makedirs(data, exist_ok=True)
    index = ["<!-- Generated by scripts/sync.py from the engine's data/ids. Do not edit. -->", "",
             "# Game data", "",
             "The game's numbers, with the [`rq.ids`](../reference/api/rq.ids.md) key and the in-game English "
             "name of each. The names come from the game itself; only names and numbers are listed.", "",
             "| Kind | Entries | What the number is |", "| --- | --- | --- |"]
    for k in model["kinds"]:
        page = DATA_PAGES[k["kind"]]
        index.append("| [%s](%s.md) | %d | %s |" % (k["title"], page, len(k["entries"]), k["what"]))
        seen = {}
        for e in k["entries"]:
            seen[e["name"]] = seen.get(e["name"], 0) + 1
        dup = sum(1 for n in seen.values() if n > 1)
        head = DETAIL.get(k["kind"])
        lines = ["<!-- Generated by scripts/sync.py from the engine's data/ids. Do not edit. -->", "",
                 "# %s" % k["title"], "",
                 "`rq.ids.%s`: %s. %d entries." % (k["kind"], k["what"], len(k["entries"])), ""]
        if dup:
            more = sum(1 for e in k["entries"] if e.get("aliases"))
            note = "%d names are used for more than one number; each of those keys ends in its number." % dup
            if more:
                note += (" %d of those numbers also have a key without the number (the one players know, or a"
                         " name of its own such as `CAPTURE_EX`), listed after the numbered key." % more)
            lines += [note, ""]
        lines += ["| Number | Key | Name |" + (" %s |" % head if head else ""),
                  "| ---: | --- | --- |" + (" --- |" if head else "")]
        for e in k["entries"]:
            key = ", ".join("`%s`" % x for x in [e["key"]] + e.get("aliases", []))
            row = "| %d | %s | %s |" % (e["no"], key, cell(e["name"]))
            if head:
                row += " %s |" % cell(e["detail"])
            lines.append(row)
        with open(os.path.join(data, page + ".md"), "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines) + "\n")
    index += ["", "To look a name up from Lua: `rq.ids.find(kind, name)`, `rq.ids.find_all(kind, text)` and "
              "`rq.ids.name(kind, no)`. Things mods define are not here: they have text ids "
              "([Numbers and ids](../guide/ids.md#text-ids))."]
    with open(os.path.join(data, "index.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(index) + "\n")


def same_tree(a, b):
    cmp = filecmp.dircmp(a, b)
    if cmp.left_only or cmp.right_only or cmp.funny_files:
        return False
    _, mismatch, errors = filecmp.cmpfiles(a, b, cmp.common_files, shallow=False)
    if mismatch or errors:
        return False
    return all(same_tree(os.path.join(a, d), os.path.join(b, d)) for d in cmp.common_dirs)


def main(argv):
    engine = os.path.join(os.path.dirname(ROOT), "RQ_modding_xsystem4")
    check = False
    args = list(argv)
    while args:
        a = args.pop(0)
        if a == "--engine" and args:
            engine = args.pop(0)
        elif a == "--check":
            check = True
        else:
            sys.exit(__doc__)
    engine = os.path.abspath(engine)

    with tempfile.TemporaryDirectory() as tmp:
        generate(engine, tmp)
        pairs = [("reference", True), ("changelog.md", False), ("data", True)]
        if check:
            bad = []
            for name, is_dir in pairs:
                new, old = os.path.join(tmp, name), os.path.join(DOCS, name)
                ok = os.path.exists(old) and (same_tree(new, old) if is_dir else filecmp.cmp(new, old, shallow=False))
                if not ok:
                    bad.append(name)
            if bad:
                print("sync --check: out of date: " + ", ".join(bad) + ". Run scripts/sync.py and commit.")
                return 1
            print("sync --check: docs match the engine")
            return 0
        for name, is_dir in pairs:
            dst = os.path.join(DOCS, name)
            if is_dir:
                shutil.rmtree(dst, ignore_errors=True)
                shutil.copytree(os.path.join(tmp, name), dst)
            else:
                shutil.copyfile(os.path.join(tmp, name), dst)
        shutil.copyfile(os.path.join(tmp, ".vitepress", "engine.json"), os.path.join(DOCS, ".vitepress", "engine.json"))
    with open(os.path.join(DOCS, ".vitepress", "engine.json"), encoding="utf-8") as f:
        info = json.load(f)
    print("sync: reference, changelog and data from RQ MOD %s (%s)" % (info["version"], info["commit"] or "no git"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
